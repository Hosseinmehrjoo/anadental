document.getElementById('dental-contact-page-form')?.addEventListener('submit', async function (e) {
  e.preventDefault();
  var form = e.currentTarget;
  var status = document.getElementById('dental-contact-page-status');
  var btn = form.querySelector('[type=submit]');
  btn.disabled = true;
  status.textContent = 'در حال ارسال…';
  status.className = 'ana-contact-form__status is-pending';
  try {
    var payload = Object.fromEntries(new FormData(form).entries());
    var res = await DentalApi.contact(payload);
    status.textContent = res.message || 'پیام ثبت شد. به‌زودی با شما تماس می‌گیریم.';
    status.className = 'ana-contact-form__status is-success';
    form.reset();
  } catch (err) {
    status.textContent = err.message || 'ارسال ممکن نشد.';
    status.className = 'ana-contact-form__status is-error';
  } finally {
    btn.disabled = false;
  }
});
</script>
